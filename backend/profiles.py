PROFILES: Tuple[EcuProfile, ...] = (EDC15_DEMO_PROFILE, EDC16_INSPECTION_PROFILE)


def profile_by_id(profile_id: str) -> EcuProfile:
    for profile in PROFILES:
        if profile.id == profile_id:
            return profile
    raise UnsupportedEcuError(f"Bilinmeyen ECU profili: {profile_id}", reason="PROFILE_NOT_FOUND")


def detect_profile(data: bytes) -> EcuProfile:
    """
    Match a binary against the registry.

    Deliberately strict: size + identification keyword match.  This prevents a
    wrong ``.bin`` (different SW version, immo dump, partial read) from being
    modified with offsets that belong to another calibration.
    """
    reasons: List[str] = []
    for profile in PROFILES:
        match, reason = profile.matches(data)
        if match:
            return profile
        reasons.append(f"{profile.id}: {reason}")
    raise UnsupportedEcuError(
        "Bu .bin dosyası için doğrulanmış bir ECU profili bulunamadı. "
        "Hiçbir offset tahmin edilmedi ve dosya değiştirilmedi.\n"
        + "\n".join(reasons),
        reason="PROFILE_NOT_FOUND",
    )
