"""
ECU profile registry
====================

This module is the single source of truth for *where* a map lives and *how* its
raw bytes must be interpreted.  No other module is allowed to invent an offset.

Engineering policy
------------------
1. A binary is never parsed "best effort" with guessed addresses.  A profile
   must match the file size, the flash identifier area and (optionally) a
   SHA-256 signature.  Otherwise :class:`UnsupportedEcuError` is raised.
2. Each definition carries a ``source`` and a ``confidence`` field.  The
   bundled EDC15 profile is a **demo profile** derived from
   ``data/edc15_19tdi.xdf`` and the synthetic stock binary generated by
   ``generate_edc15_data.py``.  It must not be treated as a universal
   EDC15P+ definition: Bosch shipped dozens of software variants with
   different offsets.
3. For production, add one profile per verified software version (e.g. the
   exact VAG part number / SW number read from the ECU) and set
   ``confidence="verified"`` only after a checksum-verified read-back on a
   real ECU.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple


class UnsupportedEcuError(ValueError):
    """Raised when a binary cannot be matched to a verified profile."""

    def __init__(self, message: str, *, reason: str = "PROFILE_NOT_FOUND"):
        super().__init__(message)
        self.reason = reason


@dataclass(frozen=True)
class MapDefinition:
    """A single calibration table inside a binary."""

    key: str
    name_tr: str
    name_de: str
    address: int
    rows: int
    cols: int
    factor: float
    unit: str
    x_name_tr: str
    y_name_tr: str
    x_axis: Tuple[float, ...]
    y_axis: Tuple[float, ...]
    physical_offset: float = 0.0
    dtype: str = "uint16"          # uint16 | uint8
    endian: str = "little"         # little (EDC15 LoHi) | big (HiLo)
    raw_min: int = 0
    raw_max: int = 0xFFFF
    baseline: Optional[float] = None  # pressure maps: value that is NOT scaled
    safe_min_pct: float = -10.0
    safe_max_pct: float = 15.0
    max_absolute_pct: float = 20.0
    source: str = "data/edc15_19tdi.xdf"
    confidence: str = "demo"

    @property
    def element_size(self) -> int:
        return 2 if self.dtype == "uint16" else 1

    @property
    def byte_length(self) -> int:
        return self.rows * self.cols * self.element_size

    @property
    def end_address(self) -> int:
        return self.address + self.byte_length

    def calibrated(self, raw):
        """Physical value = raw * factor + offset (standard ECU calibration)."""
        return raw * self.factor + self.physical_offset

    def to_raw(self, physical: float) -> int:
        """Inverse of :meth:`calibrated`, rounded and clamped to the map range."""
        raw = round((physical - self.physical_offset) / self.factor)
        return int(max(self.raw_min, min(self.raw_max, raw)))

    def as_dict(self) -> dict:
        return {
            "key": self.key,
            "name_tr": self.name_tr,
            "name_de": self.name_de,
            "address": f"0x{self.address:X}",
            "rows": self.rows,
            "cols": self.cols,
            "factor": self.factor,
            "unit": self.unit,
            "x_name_tr": self.x_name_tr,
            "y_name_tr": self.y_name_tr,
            "x_axis": list(self.x_axis),
            "y_axis": list(self.y_axis),
            "dtype": self.dtype,
            "endian": self.endian,
            "baseline": self.baseline,
            "safe_range_pct": [self.safe_min_pct, self.safe_max_pct],
            "hard_limit_pct": self.max_absolute_pct,
            "source": self.source,
            "confidence": self.confidence,
        }


@dataclass(frozen=True)
class ChecksumRegion:
    """
    A checksum-protected memory region.

    ``start`` is inclusive, ``end`` is exclusive and points at the first byte of
    the *stored* checksum.  The checksum is calculated over ``[start, end)`` and
    written at ``stored_offset`` (which normally equals ``end``).
    """

    name_tr: str
    start: int
    end: int
    stored_offset: int
    stored_size: int = 4
    algorithm: str = "sum16_words_le_u32"
    source: str = "data/edc15_19tdi.xdf"
    confidence: str = "demo"

    @property
    def data_length(self) -> int:
        return self.end - self.start

    def as_dict(self) -> dict:
        return {
            "name_tr": self.name_tr,
            "range": f"0x{self.start:X} - 0x{self.end:X}",
            "stored_offset": f"0x{self.stored_offset:X}",
            "stored_size": self.stored_size,
            "algorithm": self.algorithm,
            "source": self.source,
            "confidence": self.confidence,
        }


@dataclass(frozen=True)
class EcuProfile:
    id: str
    display_name: str
    vendor: str
    ecu_family: str
    flash_size: int
    endian: str
    identifier_offset: int
    identifier_length: int
    identifier_keywords: Tuple[str, ...]
    maps: Dict[str, MapDefinition]
    checksum_regions: Tuple[ChecksumRegion, ...]
    base_hp: int = 101
    base_torque_nm: int = 240
    source: str = "data/edc15_19tdi.xdf"
    confidence: str = "demo"
    notes: str = ""
    # False => the binary can be loaded, identified and inspected, but no map
    # bytes may be modified and no checksum may be written.  Used for ECUs we
    # can identify but have no verified map pack (XDF/DAMOS) for.
    tuning_enabled: bool = True
    # Optional secondary identification block (e.g. the Bosch software number
    # that is stored separately from the long identification string).
    software_offset: Optional[int] = None
    software_length: int = 16

    def map(self, key: str) -> MapDefinition:
        normalized = key.lower().replace("-", "_").replace(" ", "_")
        if normalized not in self.maps:
            raise KeyError(
                f"'{key}' haritası bu ECU profilinde yok. "
                f"Mevcut haritalar: {', '.join(self.maps)}"
            )
        return self.maps[normalized]

    def validate_file_size(self, size: int) -> None:
        if size != self.flash_size:
            raise UnsupportedEcuError(
                f"Dosya boyutu {size} bayt. {self.display_name} profili "
                f"{self.flash_size} bayt bekliyor. Yanlış ECU dosyası veya "
                "eksik okuma (partial read) olabilir; işlem reddedildi.",
                reason="SIZE_MISMATCH",
            )

    def identifier_text(self, data: bytes) -> str:
        raw = data[self.identifier_offset:self.identifier_offset + self.identifier_length]
        return raw.split(b"\x00", 1)[0].decode("ascii", errors="ignore").strip()

    def software_text(self, data: bytes) -> str:
        """Bosch software number stored outside the long identification block."""
        if self.software_offset is None:
            return ""
        raw = data[self.software_offset:self.software_offset + self.software_length]
        return raw.split(b"\x00", 1)[0].decode("ascii", errors="ignore").strip()

    def matches(self, data: bytes) -> Tuple[bool, str]:
        try:
            self.validate_file_size(len(data))
        except UnsupportedEcuError as exc:
            return False, str(exc)
        text = self.identifier_text(data).upper()
        if not text:
            return False, "ECU kimlik (identification) alanı boş; profil doğrulanamadı."
        for keyword in self.identifier_keywords:
            if keyword.upper() in text:
                return True, f"Kimlik alanı eşleşti: '{keyword}'"
        return False, (
            "Dosya boyutu doğru fakat kimlik alanında beklenen imza bulunamadı "
            f"({', '.join(self.identifier_keywords)}). Bilinmeyen yazılım sürümüne "
            "tahmini offset uygulanmaz."
        )

    def as_dict(self) -> dict:
        return {
            "id": self.id,
            "display_name": self.display_name,
            "vendor": self.vendor,
            "ecu_family": self.ecu_family,
            "flash_size": self.flash_size,
            "flash_size_human": f"{self.flash_size // 1024} KB",
            "endian": self.endian,
            "identifier_offset": f"0x{self.identifier_offset:X}",
            "identifier_length": self.identifier_length,
            "software_offset": (
                f"0x{self.software_offset:X}" if self.software_offset is not None else None
            ),
            "base_hp": self.base_hp,
            "base_torque_nm": self.base_torque_nm,
            "source": self.source,
            "confidence": self.confidence,
            "notes": self.notes,
            "tuning_enabled": self.tuning_enabled,
            "read_only": not self.tuning_enabled,
            "maps": {key: definition.as_dict() for key, definition in self.maps.items()},
            "checksum_regions": [region.as_dict() for region in self.checksum_regions],
        }


